"""Tests for the generated-asset reproducibility check.

``--check`` must compare regenerated bytes and chunk ids, not just counts. A
hand edit can preserve every document/chunk count while changing the text hash
embedded in a chunk id, which would leave the committed golden rows stale.
"""

import json
from pathlib import Path
from typing import cast

import pytest

from app.tools import generate_eval_assets as generator


def test_check_passes_on_committed_assets() -> None:
    assert generator.main(["--check"]) == 0


def _generated_index() -> dict[str, dict[str, str]]:
    return {
        doc_id: generator._chunk_ids_by_heading(
            content,
            f"corpus/synthetic/{doc_id}.md",
        )
        for doc_id, content in generator.build_corpus()
    }


def test_phase_c_rows_are_powered_grounded_and_isolated() -> None:
    index = _generated_index()
    rows = generator.build_golden(index)
    fact = [row for row in rows if str(row["id"]).startswith("gen_fact_phase_c_")]
    multi_hop = [row for row in rows if str(row["id"]).startswith("gen_multi_hop_phase_c_")]
    chunk_ids = {chunk_id for headings in index.values() for chunk_id in headings.values()}

    assert len(rows) == 456
    assert len(fact) == generator.PHASE_C_FACT_TEST_ROWS == 45
    assert len(multi_hop) == generator.PHASE_C_MULTI_HOP_TEST_ROWS == 201
    assert len({row["cluster_id"] for row in fact}) == generator.PHASE_C_FACT_CLUSTERS
    assert len({row["cluster_id"] for row in multi_hop}) == generator.PHASE_C_MULTI_HOP_CLUSTERS
    assert all(row["split"] == "test" for row in [*fact, *multi_hop])
    for row in [*fact, *multi_hop]:
        assert set(cast(list[str], row["expected_chunk_ids"])) <= chunk_ids

    paraphrase = [row for row in rows if row["category"] == "paraphrase"]
    assert len(paraphrase) == 30
    parents = [
        parent for row in paraphrase for parent in cast(list[str], row.get("depends_on", []))
    ]
    assert parents
    assert all(not parent.startswith("gen_fact_phase_c_") for parent in parents)


def test_check_detects_cluster_id_drift(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    _redirect_generator(monkeypatch, tmp_path)
    assert generator.main([]) == 0

    rows = [
        json.loads(line)
        for line in generator.GOLDEN_PATH.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    rows[0]["cluster_id"] = "drifted_cluster"
    generator.GOLDEN_PATH.write_text(
        "\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n",
        encoding="utf-8",
    )

    assert generator.main(["--check"]) == 1


def _redirect_generator(monkeypatch: pytest.MonkeyPatch, root: Path) -> None:
    corpus_dir = root / "corpus"
    monkeypatch.setattr(generator, "CORPUS_DIR", corpus_dir)
    monkeypatch.setattr(generator, "SYNTHETIC_DIR", corpus_dir / "synthetic")
    monkeypatch.setattr(generator, "GOLDEN_PATH", root / "evals" / "golden" / "questions.jsonl")
    monkeypatch.setattr(generator, "MANIFEST_PATH", corpus_dir / "synthetic" / "manifest.json")


def test_check_detects_body_drift_without_count_changes(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    _redirect_generator(monkeypatch, tmp_path)
    assert generator.main([]) == 0

    document = sorted(generator.SYNTHETIC_DIR.glob("doc_service_*.md"))[0]
    text = document.read_text(encoding="utf-8")
    assert "p99" in text
    document.write_text(text.replace("p99", "p99 ", 1), encoding="utf-8")

    assert generator.main(["--check"]) == 1
    output = capsys.readouterr().out
    assert "differs from generator output" in output


def test_check_detects_extra_generated_document(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    _redirect_generator(monkeypatch, tmp_path)
    assert generator.main([]) == 0

    (generator.SYNTHETIC_DIR / "doc_unexpected.md").write_text(
        "# Unexpected\n\nNot produced by the generator.\n",
        encoding="utf-8",
    )

    assert generator.main(["--check"]) == 1
