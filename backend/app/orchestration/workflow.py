def _passes_evidence_gate(item: Evidence, settings: Any) -> bool:
    """Apply score floors only to comparable scores.

    RRF is rank-only and is never used as evidence relevance. Hybrid and dense
    candidates carry dense cosine scores; reranked candidates carry cross-encoder
    logits. Other methods (sparse/graph/web) keep their native scores.
    """
    if item.retrieval_method == "rerank":
        return item.score >= settings.EVIDENCE_MIN_RERANK_SCORE
    if item.retrieval_method in {"hybrid", "dense"}:
        return item.score >= settings.EVIDENCE_MIN_DENSE_COSINE
    return True


# Minimal inline routing rules. These replace the former QueryRouter and keep
# only the safety abstention gate plus the small-talk/retrieval-shape decisions
# needed by the live pipeline. Exact-cache lookup lives in ``cache_node``.
SMALL_TALK_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(
        r"^(hi|hello|hey|greetings|good morning|good afternoon|good evening|howdy)[\s!.]*$",
        re.IGNORECASE,
    ),
    re.compile(
        r"^(who are you|what can you do|how are you|tell me about yourself)[\s?!.]*$",
        re.IGNORECASE,
    ),
    re.compile(r"^(thanks|thank you|bye|goodbye)[\s!.]*$", re.IGNORECASE),
)

UNSAFE_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\b(self[- ]?harm|suicide|kill myself)\b", re.IGNORECASE),
    re.compile(
        r"\b(how to|instructions? for)\b.*\b(bomb|explosive|weapon|firearm)\b", re.IGNORECASE
    ),
    re.compile(r"\b(make|build|synthesize)\b.*\b(meth|fentanyl|nerve agent)\b", re.IGNORECASE),
    re.compile(r"\b(ddos|ransomware|malware)\b.*\b(how to|instructions?|deploy)\b", re.IGNORECASE),
)

GROUNDED_ONLY_UNANSWERABLE_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\b(arr|gross profit|revenue|fiscal year)\b", re.IGNORECASE),
    re.compile(r"\b(aws region|kubernetes cluster|cloud provider)\b", re.IGNORECASE),
    re.compile(r"\b(snowflake|data lake|at-rest encryption)\b", re.IGNORECASE),
)

MULTI_HOP_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\b(upstream|downstream|depends? on|dependency chain)\b", re.IGNORECASE),
    re.compile(r"\b(incident|postmortem|outage)\b.*\b(root cause|failed|impact)", re.IGNORECASE),
    re.compile(r"\bwhat service failed\b", re.IGNORECASE),
    re.compile(r"\bwho was assigned the remediation\b", re.IGNORECASE),
    re.compile(r"\bconnected to|related to|linked to\b.*\b(incident|change|service)", re.IGNORECASE),
)

GLOBAL_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\b(summarize|summary across|overview of all)\b", re.IGNORECASE),
    re.compile(r"\b(across systems|common patterns|mechanisms exist)\b", re.IGNORECASE),
    re.compile(
        r"\b(describe the remediation action items|action items and their owners)\b",
        re.IGNORECASE,
    ),
)


def classify_route(query: str, answer_policy: AnswerPolicy = "grounded_only") -> str:
    """Return the inline route decision for a query.

    Unsafe requests always abstain. Out-of-domain requests abstain only for
    ``grounded_only`` so ``grounded_plus_web`` can still use web evidence.
    """
    cleaned = query.strip()
    if any(pattern.search(cleaned) for pattern in SMALL_TALK_PATTERNS):
        return "small_talk"
    if any(pattern.search(cleaned) for pattern in UNSAFE_PATTERNS):
        return "abstain"
    if answer_policy == "grounded_only" and any(
        pattern.search(cleaned) for pattern in GROUNDED_ONLY_UNANSWERABLE_PATTERNS
    ):
        return "abstain"
    if any(pattern.search(cleaned) for pattern in MULTI_HOP_PATTERNS):
        return "graph"
    if any(pattern.search(cleaned) for pattern in GLOBAL_PATTERNS):
        return "hybrid"
    return "vector"


class RAGOrchestrator:
    """Configures and runs the LangGraph RAG pipeline with routing, caching, and bounded retry."""

    def __init__(
        self,
        hybrid_retriever: HybridRetriever | None = None,
        graph_retriever: GraphRetriever | None = None,
        exact_cache: ExactCache | None = None,
        model_gateway: ModelGateway | None = None,
        cache_enabled: bool = True,
        web_client: WebClient | None = None,
        web_ingestor: WebIngestor | None = None,
        query_history: QueryHistory | None = None,
        record_history: bool = False,
        defer_cache_history: bool = False,
    ) -> None:
        self.hybrid_retriever = hybrid_retriever or HybridRetriever()
        self.graph_retriever = graph_retriever or GraphRetriever()
        self.cache_enabled = cache_enabled
        if cache_enabled:
            self.exact_cache = exact_cache or ExactCache()
        else:
            self.exact_cache = ExactCache(enabled=False)
        self.gateway = model_gateway or ModelGateway()
        self._web_client = web_client
        self._web_ingestor = web_ingestor
        self._query_history = query_history
        # History is write-only now: it records traces for graph sync, never
        # answers. Reuse comes from the exact cache or fresh retrieval.
        self.record_history = record_history or query_history is not None
        # Cache hits can record query/answer history in the background so the
        # cache-hit SLA does not include graph/Postgres persistence work.
        self.defer_cache_history = defer_cache_history
        self._history_tasks: set[asyncio.Task[None]] = set()
        self.graph = self._build_graph()

    @property
    def web_client(self) -> WebClient:
        return self._web_client or get_web_client()

    @property
    def web_ingestor(self) -> WebIngestor:
        return self._web_ingestor or get_web_ingestor()

    @property
    def query_history(self) -> QueryHistory:
        return self._query_history or get_query_history()

    def _build_graph(self) -> Any:
        workflow = StateGraph(RAGState)

        # 0. Query Condensation Node (Multi-turn Standalone Rewriting)
        async def condense_node(state: RAGState) -> dict[str, Any]:
            raw_q = state.get("raw_query") or state.get("query", "")
            history = state.get("thread_history", [])
            rewritten, duration_ms = await condense_query(raw_q, history, self.gateway)

            rewrite_span = {
                "id": f"sp-{uuid.uuid4().hex[:6]}",
                "name": "Query Condensation: condense_query",
                "service": "QueryRewriter",
                "start_ms": 0.0,
                "duration_ms": duration_ms,
                "status": "ok",
                "meta": f"Original: '{raw_q}' -> Standalone: '{rewritten}'",
            }
            existing_spans = list(state.get("spans", []))
            existing_spans.append(rewrite_span)

            return {
                "rewritten_query": rewritten,
                "query": rewritten,
                "spans": existing_spans,
            }

        # 1. Routing Node
        def route_node(state: RAGState) -> dict[str, Any]:
            query_to_route = state.get("rewritten_query") or state["query"]
            route = classify_route(
                query_to_route,
                answer_policy=state.get("answer_policy", "grounded_only"),
            )
            route_span = {
                "id": f"sp-{uuid.uuid4().hex[:6]}",
                "name": "Boundaries: evaluate query intent",
                "service": "InlineRouter",
                "start_ms": 10.0,
                "duration_ms": 12.0,
                "status": "ok",
                "meta": f"Route: {route}",
            }
            spans = list(state.get("spans", []))
            spans.append(route_span)
            return {"route": route, "spans": spans}

        # 2. Small Talk Node (skips retrieval entirely)
        def small_talk_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Small Talk: direct response",
                    "service": "InlineRouter",
                    "start_ms": 15.0,
                    "duration_ms": 2.0,
                    "status": "ok",
                    "meta": "Conversational greeting handled without retrieval",
                }
            )
            return {
                "answer": (
                    "Hello! I am your AI assistant for the GraphRAG Intelligence Lab. "
                    "How can I help you explore documents, entities, and their relationships?"
                ),
                "evidence": [],
                "is_cached": False,
                "is_abstention": False,
                "citations_valid": True,
                "cost_usd": 0.0,
                "source_kind": "docs",
                "web_sources": [],
                "spans": spans,
            }

        # 3. Cache Node
        def cache_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))

            # A comparison run can disable the exact cache entirely:
            # a hit would return an answer produced by a different config.
            # Forced-web probes must also bypass cached doc answers.
            if not self.cache_enabled or state.get("force_web", False):
                return {"is_cached": False, "spans": spans}

            query = state.get("rewritten_query") or state["query"]
            scope = state.get("acl_scope", ACLScope.public())
            prompt_version = state.get("prompt_version", PROMPT_VERSION)
            answer_policy = state.get("answer_policy", "grounded_only")
            index_version = self.exact_cache.current_index_version(
                state.get("owner_user_id")
            )

            hit = self.exact_cache.get(
                query,
                scope,
                index_version=index_version,
                prompt_version=prompt_version,
                owner_user_id=state.get("owner_user_id"),
                answer_policy=answer_policy,
            )
            if hit is not None:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Exact Cache: probe",
                        "service": "ExactCache",
                        "start_ms": 22.0,
                        "duration_ms": 2.0,
                        "status": "hit",
                        "meta": "Exact match found in cache",
                    }
                )
                return {
                    "answer": hit.answer or "",
                    "evidence": hit.evidence,
                    "is_cached": True,
                    "cost_usd": 0.0,
                    "citations_valid": True,
                    "source_kind": getattr(hit, "source_kind", state.get("source_kind", "docs")),
                    "web_sources": list(getattr(hit, "web_sources", []) or []),
                    "spans": spans,
                }

            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Exact Cache: probe",
                    "service": "ExactCache",
                    "start_ms": 22.0,
                    "duration_ms": 2.0,
                    "status": "miss",
                    "meta": "Exact cache miss",
                }
            )
            return {"is_cached": False, "spans": spans}

        # 4. Retrieval Node
        async def retrieve_node(state: RAGState) -> dict[str, Any]:
            retrieval_start = time.perf_counter()
            query = state.get("rewritten_query") or state["query"]
            route = state.get("route", "vector")
            config = state.get("retrieval_config", "full")
            scope = state.get("acl_scope", ACLScope.public())
            spans = list(state.get("spans", []))

            def done(payload: dict[str, Any]) -> dict[str, Any]:
                """Attach retrieval-only time, excluding LLM and provider backoff."""
                settings = get_settings()
                if "evidence" in payload:
                    payload["evidence"] = [
                        item
                        for item in payload["evidence"]
                        if _passes_evidence_gate(item, settings)
                    ]
                payload["retrieval_latency_ms"] = round(
                    (time.perf_counter() - retrieval_start) * 1000.0, 2
                )
                return payload

            filter_criteria = RetrievalFilter(
                acl_scope=scope,
                owner_user_id=state.get("owner_user_id"),
                is_admin=state.get("is_admin", False),
            )

            # Ablation configs call exactly one retriever and never take the
            # router's graph branch. The router decision is still recorded, so
            # router accuracy remains comparable across configurations.
            if config == "dense":
                dense_evidence = await self.hybrid_retriever.search_dense(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                )
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Dense Retrieval: ANN only",
                        "service": "DenseRetriever",
                        "start_ms": 30.0,
                        "duration_ms": 20.0,
                        "status": "ok",
                        "meta": f"Retrieved {len(dense_evidence)} candidates",
                    }
                )
                return done({"evidence": dense_evidence, "path": None, "spans": spans})

            if config == "sparse":
                sparse_evidence = await self.hybrid_retriever.search_sparse(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                )
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Sparse Retrieval: BM25 only",
                        "service": "BM25Retriever",
                        "start_ms": 30.0,
                        "duration_ms": 18.0,
                        "status": "ok",
                        "meta": f"Retrieved {len(sparse_evidence)} candidates",
                    }
                )
                return done({"evidence": sparse_evidence, "path": None, "spans": spans})

            if config == "hybrid":
                hybrid_only = await self.hybrid_retriever.search(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                    rerank=False,
                )
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Hybrid Retrieval: RRF k=60 (no rerank)",
                        "service": "HybridRetriever",
                        "start_ms": 30.0,
                        "duration_ms": 26.0,
                        "status": "ok",
                        "meta": f"Retrieved {len(hybrid_only)} candidates",
                    }
                )
                return done({"evidence": hybrid_only, "path": None, "spans": spans})

            # Route to Graph if multi-hop detected. ``graph_forced`` bypasses
            # the router decision and takes this branch on every row while
            # keeping the same hybrid RRF pool and CrossEncoder reranking.
            if config == "graph_forced" or route == "graph":
                discovered_path: list[str] | None = None
                matched_entities = await _maybe_await(
                    self.graph_retriever.search_entities(
                        query, top_k=5, filter_criteria=filter_criteria
                    )
                )
                # Vector-seeded entities supplement Neo4j's literal name match.
                # Deterministic query extraction keeps GLiNER off the Ask path.
                seed_search = getattr(self.graph_retriever, "search_entity_seeds", None)
                if callable(seed_search):
                    seeds = await _maybe_await(
                        seed_search(query, top_k=5, filter_criteria=filter_criteria)
                    )
                    known_names = {
                        str(entity.get("name", "")).lower()
                        for entity in matched_entities
                        if isinstance(entity, dict)
                    }
                    for seed in seeds or []:
                        name = str(seed.get("name") or "")
                        if not name or name.lower() in known_names:
                            continue
                        matched_entities.append(
                            {
                                "id": seed.get("entity_id"),
                                "name": name,
                                "type": seed.get("entity_type"),
                            }
                        )
                        known_names.add(name.lower())
                if len(matched_entities) >= 2:
                    ent_a = matched_entities[0]["name"]
                    ent_b = matched_entities[1]["name"]
                    discovered_path = await _maybe_await(
                        self.graph_retriever.find_path(
                            ent_a, ent_b, filter_criteria=filter_criteria
                        )
                    )

                if not discovered_path:
                    # Try other pairs from the query-matched entities. No
                    # hard-coded corpus identities or team-specific heuristics.
                    names = [
                        entity["name"]
                        for entity in matched_entities[:4]
                        if isinstance(entity, dict) and entity.get("name")
                    ]
                    for index, source in enumerate(names):
                        for target in names[index + 1 :]:
                            discovered_path = await _maybe_await(
                                self.graph_retriever.find_path(
                                    source, target, filter_criteria=filter_criteria
                                )
                            )
                            if discovered_path:
                                break
                        if discovered_path:
                            break

                graph_evidence = (
                    await _maybe_await(
                        self.graph_retriever.retrieve_path_evidence(
                            discovered_path, filter_criteria=filter_criteria
                        )
                    )
                    if discovered_path
                    else []
                )

                # Fuse all branches first: dense + sparse RRF candidates plus
                # graph path evidence. Rerank the combined, deduplicated pool
                # once, and only then cut to top-k. Graph evidence must never be
                # appended after the reranker.
                combined_evidence = await self.hybrid_retriever.search(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                    rerank=True,
                    extra_candidates=graph_evidence,
                )

                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Graph Traversal: Cypher BFS",
                        "service": "Neo4jGraph",
                        "start_ms": 30.0,
                        "duration_ms": 32.0,
                        "status": "ok",
                        "meta": f"Path: {' -> '.join(discovered_path) if discovered_path else 'none'}",
                    }
                )
                return done(
                    {
                        "evidence": combined_evidence,
                        "path": discovered_path,
                        "spans": spans,
                    }
                )

            # Default to hybrid RRF search with CrossEncoder reranking
            evidence = await self.hybrid_retriever.search(
                query=query,
                top_k=5,
                filter_criteria=filter_criteria,
                rerank=True,
            )
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Hybrid Retrieval: RRF k=60 + CrossEncoder",
                    "service": "HybridRetriever",
                    "start_ms": 30.0,
                    "duration_ms": 28.0,
                    "status": "ok",
                    "meta": f"Retrieved {len(evidence)} candidates",
                }
            )
            return done({"evidence": evidence, "path": None, "spans": spans})

        # 5. Abstention Node
        def abstain_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Boundary Gate: enforce abstention",
                    "service": "SafetyGate",
                    "start_ms": 30.0,
                    "duration_ms": 4.0,
                    "status": "warning",
                    "meta": "Honest abstention triggered - out-of-domain query or zero evidence",
                }
            )
            return {
                "answer": ABSTENTION_ANSWER,
                "is_abstention": True,
                "citations_valid": True,
                "cost_usd": 0.0,
                "source_kind": "docs",
                "web_sources": [],
                "spans": spans,
            }

        # 5a. Retrieval-only terminal node. It never calls the generation model;
        # multi-turn condensation has already happened in condense_step.
        def retrieval_only_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Retrieval Only: skip answer generation",
                    "service": "EvalHarness",
                    "start_ms": 30.0,
                    "duration_ms": 0.0,
                    "status": "ok",
                    "meta": f"Scored {len(state.get('evidence', []))} evidence items",
                }
            )
            return {"answer": "", "is_abstention": False, "spans": spans}

        # 5b. Web fallback Node (only reached when retrieval returned no evidence)
        @timed_async_stage("web")
        async def web_node(state: RAGState) -> dict[str, Any]:
            query = state.get("rewritten_query") or state["query"]
            spans = list(state.get("spans", []))
            started = time.perf_counter()
            pages: list[WebPage] = []
            try:
                pages = await self.web_client.gather(query)
            except Exception as exc:
                logger.warning("Web grounding failed for %r: %s", query, exc)
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Web Grounding: unavailable",
                        "service": "graspreach",
                        "start_ms": 62.0,
                        "duration_ms": round((time.perf_counter() - started) * 1000.0, 2),
                        "status": "warning",
                        "meta": str(exc)[:200],
                    }
                )
                return {
                    "evidence": [],
                    "source_kind": "unverified",
                    "web_pages": [],
                    "web_sources": [],
                    "web_error": str(exc),
                    "web_fallback_reason": None,
                    "spans": spans,
                }

            if not pages:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Web Grounding: no results",
                        "service": "graspreach",
                        "start_ms": 62.0,
                        "duration_ms": round((time.perf_counter() - started) * 1000.0, 2),
                        "status": "warning",
                        "meta": "No usable web pages; answering from model knowledge",
                    }
                )
                return {
                    "evidence": [],
                    "source_kind": "unverified",
                    "web_pages": [],
                    "web_sources": [],
                    "web_error": "no web results",
                    "web_fallback_reason": None,
                    "spans": spans,
                }

            page_dicts = [
                {
                    "url": page.url,
                    "title": page.title,
                    "text": page.text,
                    "fetched_at": page.fetched_at,
                    "provider": page.provider,
                }
                for page in pages
            ]
            web_sources = [
                {
                    "url": page.url,
                    "title": page.title,
                    "fetched_at": page.fetched_at,
                    "provider": page.provider,
                    "source_kind": "web",
                }
                for page in pages
            ]

            try:
                evidence = await self.web_ingestor.ingest(
                    pages=pages,
                    owner_user_id=state.get("owner_user_id"),
                    acl_scope=state.get("acl_scope"),
                )
            except Exception as exc:
                logger.exception("Web write-back failed; using fetched pages for this answer only")
                evidence = [
                    Evidence(
                        chunk_id=f"web_{hashlib.sha256(page.url.encode()).hexdigest()[:12]}",
                        doc_id=f"web:{page.url}",
                        text=page.text[:4000],
                        score=1.0,
                        retrieval_method="web",
                        provenance=Provenance.from_agent(page.url, confidence=0.7),
                    )
                    for page in pages
                ]
                web_sources[-1]["write_back_error"] = str(exc)[:200] if web_sources else None

            staged_count = len(evidence)
            async with timed_stage("web_select"):
                evidence = await select_top_web_chunks(query, evidence)
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Web Grounding: search + fetch + write-back",
                    "service": "graspreach",
                    "start_ms": 62.0,
                    "duration_ms": round((time.perf_counter() - started) * 1000.0, 2),
                    "status": "ok",
                    "meta": (
                        f"Fetched {len(pages)} pages, staged {staged_count} web chunks, "
                        f"selected {len(evidence)}"
                    ),
                }
            )
            return {
                "evidence": evidence,
                "source_kind": "web",
                "web_pages": page_dicts,
                "web_sources": web_sources,
                "web_error": None,
                "web_fallback_reason": None,
                "spans": spans,
            }

        # 6. Generation Node
        async def generate_node(state: RAGState) -> dict[str, Any]:
            evidence = state.get("evidence", [])
            query = state.get("rewritten_query") or state["query"]
            retry_count = state.get("retry_count", 0)
            spans = list(state.get("spans", []))
            settings = get_settings()
            source_kind: AnswerSourceKind = state.get("source_kind", "docs")
            web_sources = list(state.get("web_sources", []) or [])

            if source_kind == "unverified":
                prompt = (
                    f"Question: {query}\n\n"
                    "Instructions:\n"
                    "1. No retrieved documents or fetched web pages were available.\n"
                    "2. Answer from general model knowledge only.\n"
                    "3. Begin with 'Unverified:' and do not invent citations or source URLs.\n"
                )
            elif source_kind == "web":
                context_block = wrap_context_for_prompt(evidence)
                source_lines = "\n".join(
                    f"- [{src.get('url')}] {src.get('title', '')}".rstrip()
                    for src in web_sources
                    if src.get("url")
                )
                prompt = (
                    f"{context_block}\n\n"
                    f"Fetched web sources:\n{source_lines}\n\n"
                    f"Question: {query}\n\n"
                    "Instructions:\n"
                    "1. Answer using the fetched web pages above and general knowledge.\n"
                    "2. Cite every web-sourced claim with the bracketed URL, e.g. [https://example.com].\n"
                    "3. Do not cite documents that were not provided.\n"
                )
            else:
                prompt = (
                    f"{wrap_context_for_prompt(evidence)}\n\n"
                    f"Question: {query}\n\n"
                    "Instructions:\n"
                    "1. Answer the question using ONLY the provided reference documents.\n"
                    "2. Every claim must have inline bracket citations pointing to the chunk IDs, e.g. [chunk_id].\n"
                    f"3. If the context does not contain the answer, reply with exactly {NOT_FOUND_MARKER} and nothing else.\n"
                )

            # In test mode without API key, use deterministic fallback
            mock_ans: str | None = None
            if settings.APP_ENV == "test" and not settings.GEMINI_API_KEY:
                if source_kind == "unverified":
                    mock_ans = (
                        "Unverified: I do not have retrieved documents or web sources "
                        "for this question."
                    )
                elif source_kind == "web" and evidence:
                    first_url = evidence[0].provenance.source_uri
                    mock_ans = f"Based on fetched web sources, {evidence[0].text[:300]} [{first_url}]"
                elif evidence:
                    chunk_citations = " ".join(f"[{ev.chunk_id}]" for ev in evidence[:2])
                    mock_ans = (
                        f"Based on system documentation, {evidence[0].text} {chunk_citations}"
                    )
                else:
                    mock_ans = "I do not have sufficient information to answer this question."

            gen_start = time.perf_counter()
            token_sink = state.get("token_sink")
            with telemetry.get_tracer().start_as_current_span("llm.completion") as llm_span:
                if token_sink is not None:
                    resp = await self.gateway.stream_complete(
                        prompt=prompt, mock_response=mock_ans, on_token=token_sink
                    )
                else:
                    resp = await self.gateway.complete(prompt=prompt, mock_response=mock_ans)
                telemetry.record_llm_usage(llm_span, resp)
            gen_dur = round((time.perf_counter() - gen_start) * 1000.0, 2)
            record_stage("llm", gen_dur)

            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": f"LLM Generation: {resp.model}",
                    "service": "ModelGateway",
                    "start_ms": 62.0,
                    "duration_ms": max(gen_dur, 20.0),
                    "status": "ok",
                    "meta": f"Tokens: {resp.usage.completion_tokens}, Cost: ${resp.usage.cost_usd:.6f}",
                }
            )

            policy = state.get("answer_policy", "grounded_only")
            not_found = (
                source_kind == "docs"
                and NOT_FOUND_MARKER in resp.content.strip().upper()
            )
            if not_found:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Evidence Gate: NOT_FOUND",
                        "service": "GroundingPolicy",
                        "start_ms": 62.0,
                        "duration_ms": 0.0,
                        "status": "warning",
                        "meta": (
                            "Grounded context did not answer the question; "
                            f"policy={policy}"
                        ),
                    }
                )
                if policy == "grounded_plus_web":
                    return {
                        "answer": "",
                        "evidence": [],
                        "cost_usd": state.get("cost_usd", 0.0) + resp.usage.cost_usd,
                        "retry_count": retry_count + 1,
                        "source_kind": "docs",
                        "web_sources": [],
                        "web_fallback_reason": "not_found",
                        "spans": spans,
                    }
                return {
                    "answer": ABSTENTION_ANSWER,
                    "is_abstention": True,
                    "citations_valid": True,
                    "cost_usd": state.get("cost_usd", 0.0) + resp.usage.cost_usd,
                    "retry_count": retry_count + 1,
                    "source_kind": "docs",
                    "web_sources": [],
                    "web_fallback_reason": None,
                    "spans": spans,
                }

            # Verify citations
            cit_result = verify_claim_citations(
                answer_text=resp.content,
                evidence_list=evidence,
                is_abstention=False,
                require_citations=source_kind != "unverified",
            )

            # Populate the exact cache on successful generation (for live queries)
            if resp.content and evidence and cit_result.is_valid:
                query_to_cache = state.get("rewritten_query") or state["query"]
                ans_obj = Answer(
                    query=query_to_cache,
                    answer=resp.content,
                    evidence=evidence,
                    is_abstention=False,
                    router_strategy=state.get("route", "vector"),
                    cost_usd=state.get("cost_usd", 0.0) + resp.usage.cost_usd,
                    latency_ms=0.0,
                    source_kind=source_kind,
                    web_sources=web_sources,
                )
                scope = state.get("acl_scope", ACLScope.public())
                prompt_version = state.get("prompt_version", PROMPT_VERSION)
                self.exact_cache.set(
                    query_to_cache,
                    ans_obj,
                    scope,
                    index_version=self.exact_cache.current_index_version(
                        state.get("owner_user_id")
                    ),
                    prompt_version=prompt_version,
                    owner_user_id=state.get("owner_user_id"),
                    answer_policy=state.get("answer_policy", "grounded_only"),
                )

            return {
                "answer": resp.content,
                "cost_usd": state.get("cost_usd", 0.0) + resp.usage.cost_usd,
                "citations_valid": cit_result.is_valid,
                "retry_count": retry_count + 1,
                "source_kind": source_kind,
                "web_sources": web_sources,
                "web_fallback_reason": None,
                "spans": spans,
            }

        # Register nodes in graph. Each node is wrapped in one OTel span.
        workflow.add_node("condense_step", telemetry.traced_node("condense_step", condense_node))
        workflow.add_node("route_step", telemetry.traced_node("route_step", route_node))
        workflow.add_node(
            "small_talk_step", telemetry.traced_node("small_talk_step", small_talk_node)
        )
        workflow.add_node("cache_step", telemetry.traced_node("cache_step", cache_node))
        workflow.add_node("retrieve_step", telemetry.traced_node("retrieve_step", retrieve_node))
        workflow.add_node("web_step", telemetry.traced_node("web_step", web_node))
        workflow.add_node("abstain_step", telemetry.traced_node("abstain_step", abstain_node))
        workflow.add_node(
            "retrieval_only_step",
            telemetry.traced_node("retrieval_only_step", retrieval_only_node),
        )
        workflow.add_node("generate_step", telemetry.traced_node("generate_step", generate_node))

        # Wire edges: start at condense_step
        workflow.set_entry_point("condense_step")
        workflow.add_edge("condense_step", "route_step")

        def route_decision(state: RAGState) -> str:
            route = state.get("route", "vector")
            if state.get("retrieval_config") == "graph_forced":
                return "cache_step"
            if route == "small_talk":
                return "small_talk_step"
            if route == "abstain":
                return "abstain_step"
            return "cache_step"

        workflow.add_conditional_edges("route_step", route_decision)
        workflow.add_edge("small_talk_step", END)

        def cache_decision(state: RAGState) -> str:
            if state.get("retrieval_config") == "graph_forced":
                return "retrieve_step"
            if state.get("is_cached", False):
                return END
            return "retrieve_step"

        workflow.add_conditional_edges("cache_step", cache_decision)

        def evidence_decision(state: RAGState) -> str:
            evidence = state.get("evidence", [])
            policy = state.get("answer_policy", "grounded_only")
            if state.get("retrieval_only", False):
                return "retrieval_only_step"
            if state.get("force_web", False) and policy == "grounded_plus_web":
                return "web_step"
            if not evidence:
                if policy == "grounded_plus_web":
                    return "web_step"
                return "abstain_step"
            query = state.get("rewritten_query") or state["query"]
            # grounded_plus_web never abstains here; the router has already
            # handled unsafe requests.
            if policy == "grounded_only" and asks_about_absent_entity(
                query, (item.text for item in evidence)
            ):
                return "abstain_step"
            return "generate_step"

        workflow.add_conditional_edges("retrieve_step", evidence_decision)
        workflow.add_edge("web_step", "generate_step")
        workflow.add_edge("abstain_step", END)
        workflow.add_edge("retrieval_only_step", END)

        def generate_decision(state: RAGState) -> str:
            if state.get("web_fallback_reason") == "not_found":
                return "web_step"
            return END

        workflow.add_conditional_edges("generate_step", generate_decision)

        return workflow.compile()

    async def run(
        self,
        query: str,
        acl_scope: ACLScope | None = None,
        thread_id: str | None = None,
        thread_history: list[dict[str, Any]] | None = None,
        retrieval_config: RetrievalConfig = "full",
        retrieval_only: bool = False,
        force_web: bool = False,
        owner_user_id: str | None = None,
        is_admin: bool = False,
        answer_policy: AnswerPolicy | None = None,
        token_sink: Callable[[str], None] | None = None,
    ) -> RAGState:
        """Run the workflow, collect stage timings, and persist answer metadata."""
        _timings, token = start_stage_timings()
        policy: AnswerPolicy = answer_policy or "grounded_only"
        final_state: RAGState = {}
        try:
            final_state = await self._run_inner(
                query=query,
                acl_scope=acl_scope,
                thread_id=thread_id,
                thread_history=thread_history,
                retrieval_config=retrieval_config,
                retrieval_only=retrieval_only,
                force_web=force_web,
                owner_user_id=owner_user_id,
                is_admin=is_admin,
                answer_policy=answer_policy,
                token_sink=token_sink,
            )
            # Snapshot before history persistence so the stored timings describe
            # the answer path itself. Synchronous persistence is included in the
            # response snapshot; deferred cache-hit persistence is not.
            persisted_timings = timing_snapshot()
            if self.record_history and not retrieval_only:
                metadata = build_answer_metadata(final_state, stage_timings_ms=persisted_timings)
                record_kwargs: dict[str, Any] = {
                    "session": None,
                    "raw_query": query,
                    "rewritten_query": str(final_state.get("rewritten_query") or query),
                    "answer": str(final_state.get("answer") or ""),
                    "evidence": list(final_state.get("evidence", [])),
                    "source_kind": str(final_state.get("source_kind", "docs")),
                    "web_sources": list(final_state.get("web_sources", []) or []),
                    "answer_policy": policy,
                    "acl_scope": acl_scope or ACLScope.public(),
                    "owner_user_id": owner_user_id,
                    "thread_id": thread_id,
                    "source": str(metadata["source"]),
                    "answer_path": list(metadata["answer_path"]),
                    "top_score": float(metadata["top_score"]),
                    "stage_timings_ms": dict(metadata["stage_timings_ms"]),
                    "is_abstention": bool(final_state.get("is_abstention", False)),
                }
                if self.defer_cache_history and final_state.get("is_cached", False):

                    async def record_cached_history() -> None:
                        try:
                            await self.query_history.record(**record_kwargs)
                        except Exception as exc:
                            logger.warning("Failed recording cached history: %s", exc)

                    task = asyncio.create_task(record_cached_history())
                    self._history_tasks.add(task)
                    task.add_done_callback(self._history_tasks.discard)
                else:
                    try:
                        async with timed_stage("persist"):
                            query_id, answer_id = await self.query_history.record(**record_kwargs)
                        final_state["query_id"] = query_id
                        final_state["answer_id"] = answer_id
                    except Exception as exc:
                        logger.warning("Failed recording query/answer history: %s", exc)
        finally:
            snapshot = timing_snapshot()
            end_stage_timings(token)
        final_state["stage_timings_ms"] = snapshot
        return final_state

    async def _run_inner(
        self,
        query: str,
        acl_scope: ACLScope | None = None,
        thread_id: str | None = None,
        thread_history: list[dict[str, Any]] | None = None,
        retrieval_config: RetrievalConfig = "full",
        retrieval_only: bool = False,
        force_web: bool = False,
        owner_user_id: str | None = None,
        is_admin: bool = False,
        answer_policy: AnswerPolicy | None = None,
        token_sink: Callable[[str], None] | None = None,
    ) -> RAGState:
        """Execute the compiled LangGraph workflow end-to-end."""
        start_time = time.perf_counter()
        scope = acl_scope or ACLScope.public()
        trace_id = f"tr-{uuid.uuid4().hex[:8]}"
        thread_key = thread_id or f"th-{uuid.uuid4().hex[:8]}"
        policy: AnswerPolicy = answer_policy or "grounded_only"

        initial_state: RAGState = {
            "query": query,
            "raw_query": query,
            "rewritten_query": query,
            "thread_id": thread_key,
            "thread_history": list(thread_history or []),
            "trace_id": trace_id,
            "acl_scope": scope,
            "owner_user_id": owner_user_id,
            "is_admin": is_admin,
            "retrieval_config": retrieval_config,
            "retrieval_only": retrieval_only,
            "force_web": force_web,
            "answer_policy": policy,
            "source_kind": "docs",
            "prompt_version": PROMPT_VERSION,
            "route": "vector",
            "is_cached": False,
            "evidence": [],
            "web_pages": [],
            "web_sources": [],
            "web_error": None,
            "web_fallback_reason": None,
            "query_id": None,
            "answer_id": None,
            "path": None,
            "answer": "",
            "is_abstention": False,
            "citations_valid": False,
            "retry_count": 0,
            "cost_usd": 0.0,
            "latency_ms": 0.0,
            "start_time": start_time,
            "metadata": {},
            "spans": [],
            "token_sink": token_sink,
        }

        config = {"configurable": {"thread_id": thread_key}}
        final_state = await self.graph.ainvoke(initial_state, config=config)

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0
        final_state["latency_ms"] = round(elapsed_ms, 2)
        final_state["trace_id"] = trace_id

        return final_state
