async def _maybe_await(val: Any) -> Any:
    """Await value if it is a coroutine or awaitable; otherwise return directly."""
    if inspect.isawaitable(val):
        return await val
    return val


# Cache entries are scoped to the prompt revision so a prompt change cannot
# serve an answer generated by an older template.
PROMPT_VERSION = "v1"


class RAGOrchestrator:
    """Configures and runs the LangGraph RAG pipeline with routing, caching, and bounded retry."""

    def __init__(
        self,
        hybrid_retriever: HybridRetriever | None = None,
        graph_retriever: GraphRetriever | None = None,
        exact_cache: ExactCache | None = None,
        semantic_cache: SemanticCache | None = None,
        model_gateway: ModelGateway | None = None,
        checkpointer: Any | None = None,
        cache_enabled: bool = True,
        web_client: WebClient | None = None,
        web_ingestor: WebIngestor | None = None,
        query_history: QueryHistory | None = None,
        history_enabled: bool = False,
    ) -> None:
        self.hybrid_retriever = hybrid_retriever or HybridRetriever()
        self.graph_retriever = graph_retriever or GraphRetriever()
        self.cache_enabled = cache_enabled
        if cache_enabled:
            self.exact_cache = exact_cache or ExactCache()
            self.semantic_cache = semantic_cache or SemanticCache()
        else:
            self.exact_cache = ExactCache(enabled=False)
            self.semantic_cache = SemanticCache(enabled=False)
        self.gateway = model_gateway or ModelGateway()
        self.checkpointer = checkpointer or MemorySaver()
        self._web_client = web_client
        self._web_ingestor = web_ingestor
        self._query_history = query_history
        self.history_enabled = history_enabled or query_history is not None
        self.graph = self._build_graph()

    @property
    def web_client(self) -> WebClient:
        return self._web_client or get_web_client()

    @property
    def web_ingestor(self) -> WebIngestor:
        return self._web_ingestor or get_web_ingestor()

    @property
    def query_history(self) -> QueryHistory:
        return self._query_history or get_query_history()

    def _build_graph(self) -> Any:
        workflow = StateGraph(RAGState)

        # 0. Query Condensation Node (Multi-turn Standalone Rewriting)
        async def condense_node(state: RAGState) -> dict[str, Any]:
            raw_q = state.get("raw_query") or state.get("query", "")
            history = state.get("thread_history", [])
            rewritten, duration_ms = await condense_query(raw_q, history, self.gateway)

            rewrite_span = {
                "id": f"sp-{uuid.uuid4().hex[:6]}",
                "name": "Query Condensation: condense_query",
                "service": "QueryRewriter",
                "start_ms": 0.0,
                "duration_ms": duration_ms,
                "status": "ok",
                "meta": f"Original: '{raw_q}' -> Standalone: '{rewritten}'",
            }
            existing_spans = list(state.get("spans", []))
            existing_spans.append(rewrite_span)

            return {
                "rewritten_query": rewritten,
                "query": rewritten,
                "spans": existing_spans,
            }

        # 1. Routing Node
        def route_node(state: RAGState) -> dict[str, Any]:
            query_to_route = state.get("rewritten_query") or state["query"]
            route = QueryRouter.route(
                query=query_to_route,
                exact_cache=self.exact_cache,
                semantic_cache=self.semantic_cache,
                acl_scope=state.get("acl_scope"),
                owner_user_id=state.get("owner_user_id"),
                answer_policy=state.get("answer_policy", "grounded_only"),
                prompt_version=state.get("prompt_version", PROMPT_VERSION),
            )
            route_span = {
                "id": f"sp-{uuid.uuid4().hex[:6]}",
                "name": "Router: evaluate query intent",
                "service": "QueryRouter",
                "start_ms": 10.0,
                "duration_ms": 12.0,
                "status": "ok",
                "meta": f"Route: {route}",
            }
            spans = list(state.get("spans", []))
            spans.append(route_span)
            return {"route": route, "spans": spans}

        # 1a. History Node (repeat answers come from Postgres/Neo4j, no web call)
        async def history_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            try:
                hit = await self.query_history.lookup(
                    query=state.get("rewritten_query") or state["query"],
                    owner_user_id=state.get("owner_user_id"),
                    answer_policy=state.get("answer_policy", "grounded_only"),
                )
            except Exception as exc:
                logger.warning("Query history lookup failed: %s", exc)
                hit = None

            if hit is None:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "History: lookup",
                        "service": "QueryHistory",
                        "start_ms": 14.0,
                        "duration_ms": 2.0,
                        "status": "miss",
                        "meta": "No prior answer for this owner and policy",
                    }
                )
                return {"from_graph_history": False, "spans": spans}

            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "History: lookup",
                    "service": "QueryHistory",
                    "start_ms": 14.0,
                    "duration_ms": 2.0,
                    "status": "hit",
                    "meta": f"Reusing answer {hit.answer_id} from query history",
                }
            )
            return {
                "answer": hit.answer,
                "evidence": hit.evidence,
                "is_abstention": False,
                "citations_valid": True,
                "is_cached": False,
                "cost_usd": 0.0,
                "source_kind": hit.source_kind,
                "web_sources": list(hit.web_sources or []),
                "query_id": hit.query_id,
                "answer_id": hit.answer_id,
                "from_graph_history": True,
                "route": "history",
                "spans": spans,
            }

        # 2. Small Talk Node (skips retrieval entirely)
        def small_talk_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Small Talk: direct response",
                    "service": "QueryRouter",
                    "start_ms": 15.0,
                    "duration_ms": 2.0,
                    "status": "ok",
                    "meta": "Conversational greeting handled without retrieval",
                }
            )
            return {
                "answer": (
                    "Hello! I am your AI assistant for the GraphRAG Intelligence Lab. "
                    "How can I help you explore system architecture, incidents, or team ownership?"
                ),
                "evidence": [],
                "is_cached": False,
                "is_abstention": False,
                "citations_valid": True,
                "cost_usd": 0.0,
                "source_kind": "docs",
                "web_sources": [],
                "spans": spans,
            }

        # 3. Cache Node
        def cache_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))

            # A comparison run can disable exact and semantic caching entirely:
            # a hit would return an answer produced by a different config.
            if not self.cache_enabled:
                return {"is_cached": False, "spans": spans}

            # Temporal queries bypass live cache
            if state.get("as_of_time") is not None:
                return {"is_cached": False, "spans": spans}

            query = state.get("rewritten_query") or state["query"]
            scope = state.get("acl_scope", ACLScope.public())
            prompt_version = state.get("prompt_version", PROMPT_VERSION)
            as_of = state.get("as_of_time")
            as_of_key = as_of.isoformat() if as_of else None

            # Check exact cache first. Legacy v1 entries remain readable only
            # for grounded_only; new writes always use the policy-scoped key.
            hit = None
            for probe_version in prompt_version_lookup_chain(prompt_version):
                hit = self.exact_cache.get(
                    query,
                    scope,
                    prompt_version=probe_version,
                    owner_user_id=state.get("owner_user_id"),
                )
                if hit is not None:
                    break
            if hit is not None:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Exact Cache: probe",
                        "service": "ExactCache",
                        "start_ms": 22.0,
                        "duration_ms": 2.0,
                        "status": "hit",
                        "meta": "Exact match found in cache",
                    }
                )
                return {
                    "answer": hit.answer or "",
                    "evidence": hit.evidence,
                    "is_cached": True,
                    "cost_usd": 0.0,
                    "citations_valid": True,
                    "source_kind": getattr(hit, "source_kind", state.get("source_kind", "docs")),
                    "web_sources": list(getattr(hit, "web_sources", []) or []),
                    "spans": spans,
                }

            # Check semantic cache
            sem_hit = None
            for probe_version in prompt_version_lookup_chain(prompt_version):
                sem_hit = self.semantic_cache.get(
                    query,
                    scope,
                    prompt_version=probe_version,
                    as_of=as_of_key,
                    owner_user_id=state.get("owner_user_id"),
                )
                if sem_hit is not None:
                    break
            if sem_hit is not None:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Semantic Cache: probe",
                        "service": "SemanticCache",
                        "start_ms": 22.0,
                        "duration_ms": 6.0,
                        "status": "hit",
                        "meta": "Semantic similarity hit in cache",
                    }
                )
                return {
                    "answer": sem_hit.answer or "",
                    "evidence": sem_hit.evidence,
                    "is_cached": True,
                    "cost_usd": 0.0,
                    "citations_valid": True,
                    "source_kind": getattr(sem_hit, "source_kind", state.get("source_kind", "docs")),
                    "web_sources": list(getattr(sem_hit, "web_sources", []) or []),
                    "spans": spans,
                }

            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Semantic Cache: probe",
                    "service": "SemanticCache",
                    "start_ms": 22.0,
                    "duration_ms": 6.0,
                    "status": "miss",
                    "meta": "Cache miss (sim < threshold)",
                }
            )
            return {"is_cached": False, "spans": spans}

        # 4. Retrieval Node
        async def retrieve_node(state: RAGState) -> dict[str, Any]:
            retrieval_start = time.perf_counter()
            query = state.get("rewritten_query") or state["query"]
            route = state.get("route", "vector")
            config = state.get("retrieval_config", "full")
            scope = state.get("acl_scope", ACLScope.public())
            spans = list(state.get("spans", []))

            def done(payload: dict[str, Any]) -> dict[str, Any]:
                """Attach retrieval-only time, excluding LLM and provider backoff."""
                payload["retrieval_latency_ms"] = round(
                    (time.perf_counter() - retrieval_start) * 1000.0, 2
                )
                return payload

            filter_criteria = RetrievalFilter(
                acl_scope=scope,
                user_roles=scope.allowed_roles,
                user_groups=scope.allowed_groups,
                as_of_time=state.get("as_of_time"),
            )

            # Ablation configs call exactly one retriever and never take the
            # router's graph branch. The router decision is still recorded, so
            # router accuracy remains comparable across configurations.
            if config == "dense":
                dense_evidence = await self.hybrid_retriever.search_dense(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                )
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Dense Retrieval: ANN only",
                        "service": "DenseRetriever",
                        "start_ms": 30.0,
                        "duration_ms": 20.0,
                        "status": "ok",
                        "meta": f"Retrieved {len(dense_evidence)} candidates",
                    }
                )
                return done({"evidence": dense_evidence, "path": None, "spans": spans})

            if config == "sparse":
                sparse_evidence = await self.hybrid_retriever.search_sparse(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                )
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Sparse Retrieval: BM25 only",
                        "service": "BM25Retriever",
                        "start_ms": 30.0,
                        "duration_ms": 18.0,
                        "status": "ok",
                        "meta": f"Retrieved {len(sparse_evidence)} candidates",
                    }
                )
                return done({"evidence": sparse_evidence, "path": None, "spans": spans})

            if config == "hybrid":
                hybrid_only = await self.hybrid_retriever.search(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                    rerank=False,
                )
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Hybrid Retrieval: RRF k=60 (no rerank)",
                        "service": "HybridRetriever",
                        "start_ms": 30.0,
                        "duration_ms": 26.0,
                        "status": "ok",
                        "meta": f"Retrieved {len(hybrid_only)} candidates",
                    }
                )
                return done({"evidence": hybrid_only, "path": None, "spans": spans})

            # Route to Graph if multi-hop detected. ``graph_forced`` bypasses
            # the router decision and takes this branch on every row while
            # keeping the same hybrid RRF pool and CrossEncoder reranking.
            if config == "graph_forced" or route == "graph":
                discovered_path: list[str] | None = None
                matched_entities = await _maybe_await(
                    self.graph_retriever.search_entities(
                        query, top_k=5, filter_criteria=filter_criteria
                    )
                )
                if len(matched_entities) >= 2:
                    ent_a = matched_entities[0]["name"]
                    ent_b = matched_entities[1]["name"]
                    discovered_path = await _maybe_await(
                        self.graph_retriever.find_path(
                            ent_a, ent_b, filter_criteria=filter_criteria
                        )
                    )

                if not discovered_path:
                    q_lower = query.lower()
                    if "slack" in q_lower or "knowledge graph" in q_lower or "neo4j" in q_lower:
                        discovered_path = await _maybe_await(
                            self.graph_retriever.find_path(
                                "Neo4j", "Alice Chen", filter_criteria=filter_criteria
                            )
                        )
                    elif "bob kumar" in q_lower:
                        discovered_path = await _maybe_await(
                            self.graph_retriever.find_path(
                                "Bob Kumar", "INC-2026-04", filter_criteria=filter_criteria
                            )
                        )
                    elif "outbox" in q_lower and "database" in q_lower:
                        discovered_path = await _maybe_await(
                            self.graph_retriever.find_path(
                                "Outbox", "PostgreSQL", filter_criteria=filter_criteria
                            )
                        )
                    elif "corebanking" in q_lower or "v2.4.1" in q_lower:
                        discovered_path = await _maybe_await(
                            self.graph_retriever.find_path(
                                "Dave Miller", "CoreBanking", filter_criteria=filter_criteria
                            )
                        )
                    else:
                        candidate_pairs = [
                            ("Alice Chen", "PostgreSQL"),
                            ("Bob Kumar", "INC-2026-04"),
                            ("Outbox", "PostgreSQL"),
                            ("Elena Rostova", "PaymentGateway"),
                            ("Dave Miller", "CoreBanking"),
                            ("Neo4j", "Alice Chen"),
                        ]
                        for src, tgt in candidate_pairs:
                            if src.lower() in q_lower or tgt.lower() in q_lower:
                                discovered_path = await _maybe_await(
                                    self.graph_retriever.find_path(
                                        src, tgt, filter_criteria=filter_criteria
                                    )
                                )
                                if discovered_path:
                                    break

                graph_evidence = (
                    await _maybe_await(
                        self.graph_retriever.retrieve_path_evidence(
                            discovered_path, filter_criteria=filter_criteria
                        )
                    )
                    if discovered_path
                    else []
                )

                # Fuse all branches first: dense + sparse RRF candidates plus
                # graph path evidence. Rerank the combined, deduplicated pool
                # once, and only then cut to top-k. Graph evidence must never be
                # appended after the reranker.
                combined_evidence = await self.hybrid_retriever.search(
                    query=query,
                    top_k=5,
                    filter_criteria=filter_criteria,
                    rerank=True,
                    extra_candidates=graph_evidence,
                )

                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Graph Traversal: Cypher BFS",
                        "service": "Neo4jGraph",
                        "start_ms": 30.0,
                        "duration_ms": 32.0,
                        "status": "ok",
                        "meta": f"Path: {' -> '.join(discovered_path) if discovered_path else 'none'}",
                    }
                )
                return done(
                    {
                        "evidence": combined_evidence,
                        "path": discovered_path,
                        "spans": spans,
                    }
                )

            # Default to hybrid RRF search with CrossEncoder reranking
            evidence = await self.hybrid_retriever.search(
                query=query,
                top_k=5,
                filter_criteria=filter_criteria,
                rerank=True,
            )
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Hybrid Retrieval: RRF k=60 + CrossEncoder",
                    "service": "HybridRetriever",
                    "start_ms": 30.0,
                    "duration_ms": 28.0,
                    "status": "ok",
                    "meta": f"Retrieved {len(evidence)} candidates",
                }
            )
            return done({"evidence": evidence, "path": None, "spans": spans})

        # 5. Abstention Node
        def abstain_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Boundary Gate: enforce abstention",
                    "service": "SafetyGate",
                    "start_ms": 30.0,
                    "duration_ms": 4.0,
                    "status": "warning",
                    "meta": "Honest abstention triggered - out-of-domain query or zero evidence",
                }
            )
            return {
                "answer": (
                    "I do not have sufficient information in the "
                    "provided documentation to answer this question."
                ),
                "is_abstention": True,
                "citations_valid": True,
                "cost_usd": 0.0,
                "source_kind": "docs",
                "web_sources": [],
                "spans": spans,
            }

        # 5a. Retrieval-only terminal node. It never calls the generation model;
        # multi-turn condensation has already happened in condense_step.
        def retrieval_only_node(state: RAGState) -> dict[str, Any]:
            spans = list(state.get("spans", []))
            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Retrieval Only: skip answer generation",
                    "service": "EvalHarness",
                    "start_ms": 30.0,
                    "duration_ms": 0.0,
                    "status": "ok",
                    "meta": f"Scored {len(state.get('evidence', []))} evidence items",
                }
            )
            return {"answer": "", "is_abstention": False, "spans": spans}

        # 5b. Web fallback Node (only reached when retrieval returned no evidence)
        async def web_node(state: RAGState) -> dict[str, Any]:
            query = state.get("rewritten_query") or state["query"]
            spans = list(state.get("spans", []))
            started = time.perf_counter()
            pages: list[WebPage] = []
            try:
                pages = await self.web_client.gather(query)
            except Exception as exc:
                logger.warning("Web grounding failed for %r: %s", query, exc)
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Web Grounding: unavailable",
                        "service": "graspreach",
                        "start_ms": 62.0,
                        "duration_ms": round((time.perf_counter() - started) * 1000.0, 2),
                        "status": "warning",
                        "meta": str(exc)[:200],
                    }
                )
                return {
                    "evidence": [],
                    "source_kind": "unverified",
                    "web_pages": [],
                    "web_sources": [],
                    "web_error": str(exc),
                    "spans": spans,
                }

            if not pages:
                spans.append(
                    {
                        "id": f"sp-{uuid.uuid4().hex[:6]}",
                        "name": "Web Grounding: no results",
                        "service": "graspreach",
                        "start_ms": 62.0,
                        "duration_ms": round((time.perf_counter() - started) * 1000.0, 2),
                        "status": "warning",
                        "meta": "No usable web pages; answering from model knowledge",
                    }
                )
                return {
                    "evidence": [],
                    "source_kind": "unverified",
                    "web_pages": [],
                    "web_sources": [],
                    "web_error": "no web results",
                    "spans": spans,
                }

            page_dicts = [
                {
                    "url": page.url,
                    "title": page.title,
                    "text": page.text,
                    "fetched_at": page.fetched_at,
                    "provider": page.provider,
                }
                for page in pages
            ]
            web_sources = [
                {
                    "url": page.url,
                    "title": page.title,
                    "fetched_at": page.fetched_at,
                    "provider": page.provider,
                    "source_kind": "web",
                }
                for page in pages
            ]

            try:
                evidence = await self.web_ingestor.ingest(
                    pages=pages,
                    owner_user_id=state.get("owner_user_id"),
                    acl_scope=state.get("acl_scope"),
                )
            except Exception as exc:
                logger.exception("Web write-back failed; using fetched pages for this answer only")
                evidence = [
                    Evidence(
                        chunk_id=f"web_{hashlib.sha256(page.url.encode()).hexdigest()[:12]}",
                        doc_id=f"web:{page.url}",
                        text=page.text[:4000],
                        score=1.0,
                        retrieval_method="web",
                        provenance=Provenance.from_agent(page.url, confidence=0.7),
                    )
                    for page in pages
                ]
                web_sources[-1]["write_back_error"] = str(exc)[:200] if web_sources else None

            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": "Web Grounding: search + fetch + write-back",
                    "service": "graspreach",
                    "start_ms": 62.0,
                    "duration_ms": round((time.perf_counter() - started) * 1000.0, 2),
                    "status": "ok",
                    "meta": f"Fetched {len(pages)} pages, staged {len(evidence)} web chunks",
                }
            )
            return {
                "evidence": evidence,
                "source_kind": "web",
                "web_pages": page_dicts,
                "web_sources": web_sources,
                "web_error": None,
                "spans": spans,
            }

        # 6. Generation Node
        async def generate_node(state: RAGState) -> dict[str, Any]:
            evidence = state.get("evidence", [])
            query = state.get("rewritten_query") or state["query"]
            retry_count = state.get("retry_count", 0)
            spans = list(state.get("spans", []))
            settings = get_settings()
            source_kind: AnswerSourceKind = state.get("source_kind", "docs")
            web_sources = list(state.get("web_sources", []) or [])

            if source_kind == "unverified":
                prompt = (
                    f"Question: {query}\n\n"
                    "Instructions:\n"
                    "1. No retrieved documents or fetched web pages were available.\n"
                    "2. Answer from general model knowledge only.\n"
                    "3. Begin with 'Unverified:' and do not invent citations or source URLs.\n"
                )
            elif source_kind == "web":
                context_block = wrap_context_for_prompt(evidence)
                source_lines = "\n".join(
                    f"- [{src.get('url')}] {src.get('title', '')}".rstrip()
                    for src in web_sources
                    if src.get("url")
                )
                prompt = (
                    f"{context_block}\n\n"
                    f"Fetched web sources:\n{source_lines}\n\n"
                    f"Question: {query}\n\n"
                    "Instructions:\n"
                    "1. Answer using the fetched web pages above and general knowledge.\n"
                    "2. Cite every web-sourced claim with the bracketed URL, e.g. [https://example.com].\n"
                    "3. Do not cite documents that were not provided.\n"
                )
            else:
                prompt = (
                    f"{wrap_context_for_prompt(evidence)}\n\n"
                    f"Question: {query}\n\n"
                    "Instructions:\n"
                    "1. Answer the question using ONLY the provided reference documents.\n"
                    "2. Every claim must have inline bracket citations pointing to the chunk IDs, e.g. [chunk_id].\n"
                    "3. If the context does not contain the answer, reply that you do not have sufficient information.\n"
                )

            # In test mode without API key, use deterministic fallback
            mock_ans: str | None = None
            if settings.APP_ENV == "test" and not settings.GEMINI_API_KEY:
                if source_kind == "unverified":
                    mock_ans = (
                        "Unverified: I do not have retrieved documents or web sources "
                        "for this question."
                    )
                elif source_kind == "web" and evidence:
                    first_url = evidence[0].provenance.source_uri
                    mock_ans = f"Based on fetched web sources, {evidence[0].text[:300]} [{first_url}]"
                elif evidence:
                    chunk_citations = " ".join(f"[{ev.chunk_id}]" for ev in evidence[:2])
                    mock_ans = (
                        f"Based on system documentation, {evidence[0].text} {chunk_citations}"
                    )
                else:
                    mock_ans = "I do not have sufficient information to answer this question."

            gen_start = time.perf_counter()
            resp = await self.gateway.complete(prompt=prompt, mock_response=mock_ans)
            gen_dur = round((time.perf_counter() - gen_start) * 1000.0, 2)

            spans.append(
                {
                    "id": f"sp-{uuid.uuid4().hex[:6]}",
                    "name": f"LLM Generation: {resp.model}",
                    "service": "ModelGateway",
                    "start_ms": 62.0,
                    "duration_ms": max(gen_dur, 20.0),
                    "status": "ok",
                    "meta": f"Tokens: {resp.usage.completion_tokens}, Cost: ${resp.usage.cost_usd:.6f}",
                }
            )

            # Verify citations
            cit_result = verify_claim_citations(
                answer_text=resp.content,
                evidence_list=evidence,
                is_abstention=False,
                require_citations=source_kind != "unverified",
            )

            # Populate exact and semantic cache on successful generation (for live queries)
            if (
                resp.content
                and evidence
                and cit_result.is_valid
                and state.get("as_of_time") is None
            ):
                query_to_cache = state.get("rewritten_query") or state["query"]
                ans_obj = Answer(
                    query=query_to_cache,
                    answer=resp.content,
                    evidence=evidence,
                    is_abstention=False,
                    router_strategy=state.get("route", "vector"),
                    cost_usd=state.get("cost_usd", 0.0) + resp.usage.cost_usd,
                    latency_ms=0.0,
                    source_kind=source_kind,
                    web_sources=web_sources,
                )
                scope = state.get("acl_scope", ACLScope.public())
                prompt_version = state.get("prompt_version", PROMPT_VERSION)
                as_of = state.get("as_of_time")
                self.exact_cache.set(
                    query_to_cache,
                    ans_obj,
                    scope,
                    prompt_version=prompt_version,
                    owner_user_id=state.get("owner_user_id"),
                )
                self.semantic_cache.set(
                    query_to_cache,
                    ans_obj,
                    scope,
                    prompt_version=prompt_version,
                    as_of=as_of.isoformat() if as_of else None,
                    owner_user_id=state.get("owner_user_id"),
                )

            return {
                "answer": resp.content,
                "cost_usd": state.get("cost_usd", 0.0) + resp.usage.cost_usd,
                "citations_valid": cit_result.is_valid,
                "retry_count": retry_count + 1,
                "source_kind": source_kind,
                "web_sources": web_sources,
                "spans": spans,
            }

        # Register nodes in graph
        workflow.add_node("condense_step", condense_node)
        workflow.add_node("route_step", route_node)
        workflow.add_node("history_step", history_node)
        workflow.add_node("small_talk_step", small_talk_node)
        workflow.add_node("cache_step", cache_node)
        workflow.add_node("retrieve_step", retrieve_node)
        workflow.add_node("web_step", web_node)
        workflow.add_node("abstain_step", abstain_node)
        workflow.add_node("retrieval_only_step", retrieval_only_node)
        workflow.add_node("generate_step", generate_node)

        # Wire edges: start at condense_step
        workflow.set_entry_point("condense_step")
        workflow.add_edge("condense_step", "route_step")

        def route_decision(state: RAGState) -> str:
            route = state.get("route", "vector")
            if state.get("retrieval_config") == "graph_forced":
                return "cache_step"
            if route == "small_talk":
                return "small_talk_step"
            if route == "abstain":
                return "abstain_step"
            if (
                self.history_enabled
                and not state.get("retrieval_only", False)
                and state.get("as_of_time") is None
            ):
                return "history_step"
            return "cache_step"

        workflow.add_conditional_edges("route_step", route_decision)

        def history_decision(state: RAGState) -> str:
            if state.get("from_graph_history", False):
                return END
            return "cache_step"

        workflow.add_conditional_edges("history_step", history_decision)
        workflow.add_edge("small_talk_step", END)

        def cache_decision(state: RAGState) -> str:
            if state.get("retrieval_config") == "graph_forced":
                return "retrieve_step"
            if state.get("is_cached", False):
                return END
            return "retrieve_step"

        workflow.add_conditional_edges("cache_step", cache_decision)

        def evidence_decision(state: RAGState) -> str:
            evidence = state.get("evidence", [])
            policy = state.get("answer_policy", "grounded_only")
            if state.get("retrieval_only", False):
                return "retrieval_only_step"
            if not evidence:
                if policy == "grounded_plus_web":
                    return "web_step"
                return "abstain_step"
            query = state.get("rewritten_query") or state["query"]
            # grounded_plus_web never abstains here; the router has already
            # handled unsafe requests.
            if policy == "grounded_only" and asks_about_absent_entity(
                query, (item.text for item in evidence)
            ):
                return "abstain_step"
            return "generate_step"

        workflow.add_conditional_edges("retrieve_step", evidence_decision)
        workflow.add_edge("web_step", "generate_step")
        workflow.add_edge("abstain_step", END)
        workflow.add_edge("retrieval_only_step", END)
        workflow.add_edge("generate_step", END)

        return workflow.compile(checkpointer=self.checkpointer)

    async def run(
        self,
        query: str,
        acl_scope: ACLScope | None = None,
        as_of_time: datetime | None = None,
        thread_id: str | None = None,
        thread_history: list[dict[str, Any]] | None = None,
        retrieval_config: RetrievalConfig = "full",
        retrieval_only: bool = False,
        owner_user_id: str | None = None,
        answer_policy: AnswerPolicy | None = None,
    ) -> RAGState:
        """Execute the compiled LangGraph workflow end-to-end."""
        start_time = time.perf_counter()
        scope = acl_scope or ACLScope.public()
        trace_id = f"tr-{uuid.uuid4().hex[:8]}"
        thread_key = thread_id or f"th-{uuid.uuid4().hex[:8]}"
        policy: AnswerPolicy = answer_policy or "grounded_only"

        initial_state: RAGState = {
            "query": query,
            "raw_query": query,
            "rewritten_query": query,
            "thread_id": thread_key,
            "thread_history": list(thread_history or []),
            "trace_id": trace_id,
            "acl_scope": scope,
            "owner_user_id": owner_user_id,
            "as_of_time": as_of_time,
            "retrieval_config": retrieval_config,
            "retrieval_only": retrieval_only,
            "answer_policy": policy,
            "source_kind": "docs",
            "prompt_version": f"{PROMPT_VERSION}:{policy}",
            "route": "vector",
            "is_cached": False,
            "from_graph_history": False,
            "evidence": [],
            "web_pages": [],
            "web_sources": [],
            "web_error": None,
            "query_id": None,
            "answer_id": None,
            "path": None,
            "answer": "",
            "is_abstention": False,
            "citations_valid": False,
            "retry_count": 0,
            "cost_usd": 0.0,
            "latency_ms": 0.0,
            "start_time": start_time,
            "metadata": {},
            "spans": [],
        }

        config = {"configurable": {"thread_id": thread_key}}
        final_state = await self.graph.ainvoke(initial_state, config=config)

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0
        final_state["latency_ms"] = round(elapsed_ms, 2)
        final_state["trace_id"] = trace_id

        if self.history_enabled and not retrieval_only and not final_state.get(
            "from_graph_history", False
        ):
            try:
                query_id, answer_id = await self.query_history.record(
                    session=None,
                    raw_query=query,
                    rewritten_query=str(final_state.get("rewritten_query") or query),
                    answer=str(final_state.get("answer") or ""),
                    evidence=list(final_state.get("evidence", [])),
                    source_kind=str(final_state.get("source_kind", "docs")),
                    web_sources=list(final_state.get("web_sources", []) or []),
                    answer_policy=policy,
                    acl_scope=scope,
                    owner_user_id=owner_user_id,
                    thread_id=thread_id,
                    is_abstention=bool(final_state.get("is_abstention", False)),
                )
                final_state["query_id"] = query_id
                final_state["answer_id"] = answer_id
            except Exception as exc:
                logger.warning("Failed recording query/answer history: %s", exc)

        return final_state
